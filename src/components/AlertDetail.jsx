import React from 'react';

function formatTimestamp(iso) {
  if (!iso) return '—';
  const d = new Date(iso);
  return d.toUTCString();
}

export default function AlertDetail({ alert }) {
  if (!alert) {
    return (
      <div className="alert-detail alert-detail--empty">
        <p>Select an alert to view details.</p>
      </div>
    );
  }

  const batteryLevel = typeof alert.batteryLevel === 'number' ? alert.batteryLevel : null;

  return (
    <div className="alert-detail">
      <div className="alert-detail__row">
        <div className="alert-detail__field">
          <span className="alert-detail__label">Device ID</span>
          <span className="alert-detail__value alert-detail__value--mono">{alert.deviceId || '—'}</span>
        </div>
        <div className="alert-detail__field">
          <span className="alert-detail__label">Status</span>
          <span className="alert-detail__value">{alert.status || '—'}</span>
        </div>
        <div className="alert-detail__field">
          <span className="alert-detail__label">Battery</span>
          <span className="alert-detail__value">
            {batteryLevel !== null ? `${batteryLevel}%` : '—'}
          </span>
        </div>
      </div>

      <div className="alert-detail__row">
        <div className="alert-detail__field alert-detail__field--wide">
          <span className="alert-detail__label">Coordinates</span>
          <span className="alert-detail__value alert-detail__value--mono alert-detail__value--large">
            {alert.latitude?.toFixed(6)}° , {alert.longitude?.toFixed(6)}°
          </span>
        </div>
      </div>

      <div className="alert-detail__row">
        <div className="alert-detail__field alert-detail__field--wide">
          <span className="alert-detail__label">Received</span>
          <span className="alert-detail__value alert-detail__value--mono">
            {formatTimestamp(alert.timestamp)}
          </span>
        </div>
      </div>

      {alert.source === 'mock' && (
        <div className="alert-detail__notice">Test data — generated by mockGpsSender.js</div>
      )}
    </div>
  );
}
